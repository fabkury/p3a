"""Embeds a folder of web files into the firmware as gzipped C arrays.

    python tools/embed_static.py <source-dir> <output-dir>

Writes p3a_static_gen.c: one array per file, gzipped, and the table
p3a_static_files[] that the HTTP server looks paths up in (see
components/p3a_net/include/http_static.h). A file at <source-dir>/setup/index.html
is served at /setup/index.html.

The output depends only on the files' names and bytes (no timestamps), so the
same sources always give the same firmware. Standard library only.
"""
from __future__ import annotations

import gzip
import sys
import zlib
from pathlib import Path

CONTENT_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".txt": "text/plain; charset=utf-8",
    ".woff2": "font/woff2",
}
# Already compressed: gzipping them again only costs the browser time.
STORED = {".png", ".woff2", ".ico"}
MAX_PATH = 63


class EmbedError(Exception):
    pass


def collect(source: Path) -> list[tuple[str, Path]]:
    """(URL path, file) for every file under source, sorted by path."""
    found = []
    for path in sorted(source.rglob("*")):
        if not path.is_file():
            continue
        url = "/" + path.relative_to(source).as_posix()
        if path.suffix.lower() not in CONTENT_TYPES:
            raise EmbedError(f"{url}: no content type is known for '{path.suffix}'; add it to CONTENT_TYPES")
        if len(url) > MAX_PATH or not url.isascii() or any(c in url for c in ' "\\?#%'):
            raise EmbedError(f"{url}: a path must be plain ASCII without spaces or quotes, at most {MAX_PATH} characters")
        found.append((url, path))
    return found


def pack(data: bytes, suffix: str) -> tuple[bytes, bool]:
    if suffix in STORED:
        return data, False
    return gzip.compress(data, compresslevel=9, mtime=0), True


def c_array(data: bytes) -> str:
    lines = []
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
    return "\n".join(lines) if lines else "    0x00,"


def generate(files: list[tuple[str, Path]]) -> str:
    out = ["// GENERATED by tools/embed_static.py. Do not edit.", "",
           '#include "http_static.h"', "", "#include <stddef.h>", ""]
    rows = []
    for index, (url, path) in enumerate(files):
        raw = path.read_bytes()
        body, gzipped = pack(raw, path.suffix.lower())
        etag = f'\\"{zlib.crc32(body) & 0xFFFFFFFF:08x}\\"'
        out += [f"// {url}: {len(raw)} bytes, {len(body)} embedded",
                f"static const unsigned char s_file_{index}[] = {{", c_array(body), "};", ""]
        rows.append(f'    {{"{url}", s_file_{index}, {len(body)}, "{CONTENT_TYPES[path.suffix.lower()]}", '
                    f'"{etag}", {"true" if gzipped else "false"}}},')
    out.append("const p3a_static_file_t p3a_static_files[] = {")
    out += rows if rows else ["    {NULL, NULL, 0, NULL, NULL, false},"]
    out += ["};", f"const size_t p3a_static_file_count = {len(rows)};", ""]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__)
        return 2
    source, out_dir = Path(argv[1]), Path(argv[2])
    try:
        if not source.is_dir():
            raise EmbedError(f"{source} is not a folder")
        text = generate(collect(source))
    except EmbedError as exc:
        print(f"embed_static: {exc}", file=sys.stderr)
        return 1
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / "p3a_static_gen.c"
    if not target.exists() or target.read_text(encoding="utf-8") != text:
        target.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
